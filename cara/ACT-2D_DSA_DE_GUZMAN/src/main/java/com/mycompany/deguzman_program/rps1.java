    private void btn1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn1ActionPerformed
    
    int price = (snackCombo.getSelectedIndex() == 0) ? 22 : 25;

    // Get text from inputs
    int quan1 = Integer.parseInt(txtquantity.getText().trim());
    int cash = Integer.parseInt(txtcash.getText().trim());

    int subtot = quan1 * price;

    // Validate cash amount
    if (cash < subtot) {
        JOptionPane.showMessageDialog(this, "Insufficient cash!", "Error", JOptionPane.ERROR_MESSAGE);
        return;     
    }

    int tot = cash - subtot;

    // Update labels
    lblsubtotal.setText(subtot + " pesos");
    lblchange.setText(tot + " pesos");

    JOptionPane.showMessageDialog(this, "Thank you for ordering!", "Success", JOptionPane.INFORMATION_MESSAGE);

    }//GEN-LAST:event_btn1ActionPerformed

